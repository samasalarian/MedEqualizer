#!/usr/bin/env python3
"""
cham.py  –  MedEqualizer  |  Fairness-Aware Synthetic Data Augmentation
════════════════════════════════════════════════════════════════════════

Overview
────────
Clinical datasets such as MIMIC-III and MIMIC-IV suffer from systematic
underrepresentation of certain demographic subgroups. Models trained on
imbalanced data can exhibit degraded and inequitable performance for these
populations. cham.py (CHAMeleon) addresses this by identifying underrepresented
GENDER × ETHNICITY × AGE_GROUP subgroups and augmenting them with high-quality
synthetic records generated by a generative model.

Pipeline
────────
  1. Load real data from  data/<Dataset>/real/real.csv
  2. Identify underrepresented subgroups: any (GENDER, ETHNICITY, AGE_GROUP)
     combination whose count falls below the threshold --tau.  The gap to tau
     is the number of synthetic records to generate for that subgroup.
  3. Fit the chosen generative model on the full real dataset.
  4. For each underrepresented subgroup, run a batch generation loop
     with two quality gates:

       Gate 1 – One-Class SVM (OCSVM)
           Fitted on the real data.  Synthetic rows that fall outside
           the learned real-data boundary are discarded.
           Controlled by --nu (outlier tolerance) and --gamma (kernel width).

       Gate 2 – Real-vs-Fake Classifier
           A classifier is trained to distinguish real from synthetic rows
           within the subgroup.  If it can do so too easily (AUROC > threshold),
           the batch is low-quality and rejected.  Only batches where the
           classifier AUROC ≤ --auroc are accepted.
           Note: a higher --auroc threshold is more permissive.

     Batches are drawn until the subgroup reaches tau or MAX_ATTEMPTS is hit.
     Early stopping (OCSVM_PATIENCE) abandons subgroups where the OCSVM
     rejects 100 % of rows for several consecutive batches, avoiding wasted
     compute on groups the current parameters cannot handle.

  5. Combine accepted synthetic records with the original real data and save.
  6. Append run statistics to  data/augmentation_counts.xlsx.

Supported generative models
────────────────────────────
  ctgan     SDV CTGANSynthesizer — conditional tabular GAN (implemented)
  healthgan HealthGAN            WGAN-GP per-subgroup training
  medgan    MedGAN               (binary only — LOS re-sampled post-decode)

Key arguments
─────────────
  --dataset     mimic3 | mimic4
  --model       ctgan | healthgan | medgan
  --tau         Representation threshold. Subgroups with fewer than tau
                records are augmented up to tau.
  --nu          OCSVM outlier fraction bound (default: 0.05).
                Increase (e.g. 0.3) to be more permissive for rare subgroups.
  --gamma       OCSVM kernel width: 'scale', 'auto', or a float (default: scale).
                'auto' gives a softer boundary and helps rare subgroups pass.
  --auroc       Classifier AUROC acceptance threshold (default: 0.75).
                Batches with AUROC ≤ this value are accepted.
  --classifier  Classifier for Gate 2: random_forest (default),
                logistic_regression, gradient_boosting, decision_tree, svm.
  --workers     Number of subgroups to process in parallel (default: 1).
                Recommended: 4 on M1/M2 Mac, up to cpu_count // 2 on HPC.
  --seed        Random seed for reproducibility (default: 42).

Usage examples
──────────────
  # Default run
  python augmentation/cham.py --dataset mimic3 --model ctgan --tau 150

  # More permissive OCSVM for rare subgroups + parallel processing
  python augmentation/cham.py --dataset mimic3 --model ctgan --tau 150 \\
      --nu 0.3 --gamma auto --workers 4

  # Full parameter specification
  python augmentation/cham.py --dataset mimic4 --model ctgan --tau 200 \\
      --nu 0.1 --gamma scale --auroc 0.75 --classifier random_forest \\
      --workers 4 --seed 42

Output
──────
  data/<Dataset>/augmented/<model>/<tau>_<nu>_<gamma>_<auroc>_<classifier>.csv
  data/augmentation_counts.xlsx
"""

import argparse
import os
import sys
import numpy as np
import pandas as pd
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor, as_completed
from sklearn.preprocessing import OrdinalEncoder
from sklearn.svm import OneClassSVM
from sklearn.model_selection import train_test_split
from sklearn.metrics import roc_auc_score


# ═══════════════════════════════════════════════════════════════════════════════
# Constants
# ═══════════════════════════════════════════════════════════════════════════════

EQUITY_COLS = ['GENDER', 'ETHNICITY', 'AGE_GROUP']

SUBDATA_DROP = ['SUBJECT_ID', 'HADM_ID', 'ANCHOR_AGE', 'LOS']

MIN_SAMPLES_CLASSIFIER = 5   # minimum real/fake rows needed to run the classifier

# Early stopping: abandon a subgroup after this many consecutive
# all-zero OCSVM batches — avoids burning MAX_ATTEMPTS on hopeless groups.
OCSVM_PATIENCE = 5

# Early stopping: abandon a subgroup after this many consecutive
# Gate-2 AUROC failures — avoids retraining HealthGAN/MedGAN when the GAN
# cannot generate realistic samples regardless of attempt count.
AUROC_PATIENCE = 5


# ═══════════════════════════════════════════════════════════════════════════════
# Data preparation helpers
# ═══════════════════════════════════════════════════════════════════════════════

def get_underrepresented(df: pd.DataFrame, tau: int) -> pd.DataFrame:
    group_counts = df[EQUITY_COLS].value_counts().reset_index(name='count')
    under = group_counts[group_counts['count'] < tau].copy()
    under['gap'] = tau - under['count']
    return under.sort_values('gap', ascending=False).reset_index(drop=True)


def greedy_sigma(under: pd.DataFrame) -> dict:
    return {
        tuple(row[col] for col in EQUITY_COLS): int(row['gap'])
        for _, row in under.iterrows()
    }


def build_subdata(df: pd.DataFrame) -> pd.DataFrame:
    drop_cols = [c for c in SUBDATA_DROP if c in df.columns]
    sub = df.drop(columns=drop_cols).copy()
    sub['MORTALITY'] = sub['MORTALITY'].astype(str)
    for col in sub.select_dtypes(include=['object', 'category']).columns:
        sub[col] = sub[col].astype(str)
    return sub


# ═══════════════════════════════════════════════════════════════════════════════
# Classifier factory
# ═══════════════════════════════════════════════════════════════════════════════

def get_classifier(name: str, seed: int):
    if name == 'random_forest':
        from sklearn.ensemble import RandomForestClassifier
        return RandomForestClassifier(n_estimators=100, random_state=seed)
    elif name == 'logistic_regression':
        from sklearn.linear_model import LogisticRegression
        return LogisticRegression(solver='liblinear', C=10.0, max_iter=500,
                                  random_state=seed)
    elif name == 'gradient_boosting':
        from sklearn.ensemble import GradientBoostingClassifier
        return GradientBoostingClassifier(n_estimators=100, random_state=seed)
    elif name == 'decision_tree':
        from sklearn.tree import DecisionTreeClassifier
        return DecisionTreeClassifier(random_state=seed)
    elif name == 'svm':
        from sklearn.svm import SVC
        return SVC(probability=True, random_state=seed)
    else:
        raise ValueError(f"Unknown classifier: {name}")


# ═══════════════════════════════════════════════════════════════════════════════
# Per-subgroup worker  (top-level so it is picklable for multiprocessing)
# ═══════════════════════════════════════════════════════════════════════════════

def _run_subgroup(args_dict: dict) -> dict:
    """
    Process one (GENDER, ETHNICITY, AGE_GROUP) subgroup.  Runs in its own
    process when workers > 1, so all imports must be local or already available.

    Returns a dict with keys: combo, accepted_df, target, accepted, attempts,
    avg_auroc, log_lines.
    """
    from sdv.sampling.tabular import Condition

    combo               = args_dict['combo']
    target_count        = args_dict['target_count']
    ctgan               = args_dict['ctgan']
    encoder             = args_dict['encoder']
    subdata             = args_dict['subdata']
    nu                  = args_dict['nu']
    gamma               = args_dict['gamma']
    seed                = args_dict['seed']
    auroc_threshold     = args_dict['auroc_threshold']
    classifier_name     = args_dict['classifier_name']
    batch_size          = args_dict['batch_size']
    max_tries_per_batch = args_dict['max_tries_per_batch']
    max_attempts        = args_dict['max_attempts']
    min_subgroup_size   = args_dict.get('min_subgroup_size', 10)

    gender, ethnicity, age_group = combo
    accepted              = []
    total_rows            = 0
    attempts              = 0
    auc_scores            = []
    lines                 = []
    consecutive_zero      = 0
    consecutive_auroc_fail = 0

    lines.append(f"\n  ── Subgroup  GENDER={gender}  ETHNICITY={ethnicity}  "
                 f"AGE_GROUP={age_group}  (target: {target_count}) ──")

    real_sub = subdata[
        (subdata['GENDER']    == gender) &
        (subdata['ETHNICITY'] == ethnicity) &
        (subdata['AGE_GROUP'] == age_group)
    ].copy()

    if real_sub.empty:
        lines.append(f"    WARNING: No real rows found — skipping.")
        return dict(combo=combo, accepted_df=None, target=target_count,
                    accepted=0, attempts=0, avg_auroc=float('nan'), log_lines=lines)

    if len(real_sub) < min_subgroup_size:
        lines.append(f"    WARNING: Only {len(real_sub)} real rows — skipping (need ≥ {min_subgroup_size}).")
        return dict(combo=combo, accepted_df=None, target=target_count,
                    accepted=0, attempts=0, avg_auroc=float('nan'), log_lines=lines)

    # ── Fit per-subgroup OCSVM on this subgroup's real rows only ─────────────
    X_sub  = encoder.transform(real_sub.astype(str))
    ocsvm  = OneClassSVM(kernel='rbf', nu=nu, gamma=gamma)
    ocsvm.fit(X_sub)
    lines.append(f"    OCSVM fitted on {len(real_sub)} real rows for this subgroup.")

    while total_rows < target_count and attempts < max_attempts:
        attempts += 1

        # ── Gate 0: CTGAN sample ──────────────────────────────────────────────
        condition = Condition(
            column_values={'GENDER': gender, 'ETHNICITY': ethnicity,
                           'AGE_GROUP': age_group},
            num_rows=batch_size
        )
        try:
            sample = ctgan.sample_from_conditions(
                conditions=[condition],
                max_tries_per_batch=max_tries_per_batch
            )
        except Exception as e:
            lines.append(f"    WARNING: Sampling failed (attempt {attempts}): {e}")
            consecutive_zero += 1
            if consecutive_zero >= OCSVM_PATIENCE:
                lines.append(f"    ⏹  Early stop: OCSVM rejected 100 % for "
                             f"{consecutive_zero} consecutive batches.")
                break
            continue

        if sample.empty:
            consecutive_zero += 1
            if consecutive_zero >= OCSVM_PATIENCE:
                lines.append(f"    ⏹  Early stop: no samples generated for "
                             f"{consecutive_zero} consecutive batches.")
                break
            continue

        # ── Gate 1: One-Class SVM (per-subgroup) ─────────────────────────────
        X_synth    = encoder.transform(sample.astype(str))
        decision   = ocsvm.predict(X_synth)
        valid_rows = sample[decision == 1].copy()

        if len(valid_rows) == 0:
            consecutive_zero += 1
            lines.append(f"    [attempt {attempts:>3}] OCSVM: 0/{len(sample)} passed"
                         f"  (patience {consecutive_zero}/{OCSVM_PATIENCE})")
            if consecutive_zero >= OCSVM_PATIENCE:
                lines.append(f"   Early stop: OCSVM rejected 100 % for "
                             f"{consecutive_zero} consecutive batches.")
                break
            continue
        consecutive_zero = 0

        # ── Gate 2: Classifier quality test ───────────────────────────────────
        n_balanced  = min(len(real_sub), len(valid_rows))
        real_sample = real_sub.sample(n=n_balanced, random_state=seed).copy()
        fake_sample = valid_rows.sample(n=n_balanced, random_state=seed).copy()

        lines.append(f"    [attempt {attempts:>3}] Classifier input: "
                     f"{n_balanced} real vs {n_balanced} synthetic (balanced)")

        if n_balanced < MIN_SAMPLES_CLASSIFIER:
            n_take = min(len(valid_rows), target_count - total_rows)
            accepted.append(valid_rows.iloc[:n_take])
            total_rows += n_take
            lines.append(f"    [attempt {attempts:>3}] OCSVM: {len(valid_rows)}/{len(sample)} "
                         f"passed  | classifier skipped (too few samples) "
                         f"→ accepted {n_take}  (total: {total_rows}/{target_count})")
            continue

        real_sample['_label'] = 1
        fake_sample['_label'] = 0
        clf_data = pd.concat([real_sample, fake_sample], ignore_index=True)
        X_clf    = encoder.transform(clf_data.drop(columns=['_label']).astype(str))
        y_clf    = clf_data['_label']

        if (y_clf == 0).sum() < 2 or (y_clf == 1).sum() < 2:
            n_take = min(len(valid_rows), target_count - total_rows)
            accepted.append(valid_rows.iloc[:n_take])
            total_rows += n_take
            lines.append(f"    [attempt {attempts:>3}] OCSVM: {len(valid_rows)}/{len(sample)} "
                         f"passed  | classifier skipped (class imbalance) "
                         f"→ accepted {n_take}  (total: {total_rows}/{target_count})")
            continue

        X_train, X_test, y_train, y_test = train_test_split(
            X_clf, y_clf, test_size=0.4, stratify=y_clf, random_state=seed
        )
        clf = get_classifier(classifier_name, seed)
        clf.fit(X_train, y_train)
        auc = roc_auc_score(y_test, clf.predict_proba(X_test)[:, 1])
        auc_scores.append(auc)

        if auc <= auroc_threshold:
            consecutive_auroc_fail = 0
            n_take = min(len(valid_rows), target_count - total_rows)
            accepted.append(valid_rows.iloc[:n_take])
            total_rows += n_take
            lines.append(f"    [attempt {attempts:>3}] OCSVM: {len(valid_rows)}/{len(sample)} "
                         f"passed  | AUROC={auc:.3f} ≤ {auroc_threshold} ✅ PASS"
                         f"→ accepted {n_take}  (total: {total_rows}/{target_count})")
        else:
            consecutive_auroc_fail += 1
            lines.append(f"    [attempt {attempts:>3}] OCSVM: {len(valid_rows)}/{len(sample)} "
                         f"passed  | AUROC={auc:.3f} > {auroc_threshold} FAIL"
                         f"→ batch rejected  (AUROC patience {consecutive_auroc_fail}/{AUROC_PATIENCE})")
            if consecutive_auroc_fail >= AUROC_PATIENCE:
                lines.append(f"    ⏹  Early stop: AUROC failed for "
                             f"{consecutive_auroc_fail} consecutive attempts.")
                break

    avg_auc  = float(np.mean(auc_scores)) if auc_scores else float('nan')
    combo_df = None

    if total_rows > 0:
        combo_df = pd.concat(accepted, ignore_index=True).iloc[:target_count]
        lines.append(f"    → Final: {len(combo_df)}/{target_count} accepted  "
                     f"(avg AUROC: {avg_auc:.3f})")
    else:
        lines.append(f"    ❌ FAILED:No valid samples accepted.")

    return dict(combo=combo, accepted_df=combo_df, target=target_count,
                accepted=total_rows, attempts=attempts,
                avg_auroc=avg_auc, log_lines=lines)


# ═══════════════════════════════════════════════════════════════════════════════
# Model-specific synthesis
# ═══════════════════════════════════════════════════════════════════════════════

def synthesize_ctgan(subdata: pd.DataFrame, sigma: dict, seed: int,
                     nu: float, gamma, auroc_threshold: float,
                     classifier_name: str, workers: int,
                     batch_size: int, max_tries_per_batch: int,
                     max_attempts: int,
                     epochs: int = 300, nodes: int = 64,
                     critic: int = 5, aug_epochs: int = 1000,
                     min_subgroup_size: int = 10) -> pd.DataFrame:
    from sdv.single_table import CTGANSynthesizer
    from sdv.metadata import SingleTableMetadata
    import torch

    np.random.seed(seed)
    torch.manual_seed(seed)

    # ── Fit CTGAN ──────────────────────────────────────────────────────────────
    metadata = SingleTableMetadata()
    metadata.detect_from_dataframe(data=subdata)
    print("\n  Fitting CTGANSynthesizer ...")
    ctgan = CTGANSynthesizer(metadata)
    ctgan.fit(subdata)
    print("  Fitting complete.")

    print(f"\n  Fitting OrdinalEncoder on full subdata ...")
    encoder = OrdinalEncoder(handle_unknown='use_encoded_value', unknown_value=-1)
    encoder.fit(subdata.astype(str))
    print(f"  Encoder fitted.  OCSVM will be fitted per subgroup "
          f"(nu={nu}, gamma={gamma}).")
    print(f"\n  Processing {len(sigma)} subgroup(s) with {workers} worker(s) "
          f"(early-stop patience: {OCSVM_PATIENCE} consecutive zero batches) ...")

    # ── Build per-subgroup argument dicts ─────────────────────────────────────
    job_args = [
        dict(combo=combo, target_count=count,
             ctgan=ctgan, encoder=encoder, subdata=subdata,
             nu=nu, gamma=gamma,
             seed=seed, auroc_threshold=auroc_threshold,
             classifier_name=classifier_name,
             batch_size=batch_size,
             max_tries_per_batch=max_tries_per_batch,
             max_attempts=max_attempts,
             min_subgroup_size=min_subgroup_size)
        for combo, count in sigma.items()
    ]

    # ── Run (parallel or sequential) ──────────────────────────────────────────
    results_map = {}

    if workers > 1:
        with ThreadPoolExecutor(max_workers=workers) as pool:
            future_to_combo = {
                pool.submit(_run_subgroup, a): a['combo'] for a in job_args
            }
            for future in as_completed(future_to_combo):
                result = future.result()
                for line in result['log_lines']:
                    print(line, flush=True)
                results_map[result['combo']] = result
    else:
        for a in job_args:
            result = _run_subgroup(a)
            for line in result['log_lines']:
                print(line, flush=True)
            results_map[result['combo']] = result

    # ── Collect results in original sigma order ────────────────────────────────
    all_accepted  = []
    summary_stats = {}

    for combo in sigma:
        r = results_map.get(combo)
        if r is None:
            continue
        summary_stats[combo] = {
            'target':    r['target'],
            'accepted':  r['accepted'],
            'attempts':  r['attempts'],
            'avg_auroc': r['avg_auroc'],
        }
        if r['accepted_df'] is not None:
            all_accepted.append(r['accepted_df'])

    # ── Print summary table ────────────────────────────────────────────────────
    print("\n  ── Generation summary ──────────────────────────────────────────")
    print(f"  {'Subgroup':<70} {'Target':>7} {'Accepted':>9} {'Attempts':>9} {'Avg AUROC':>10}")
    print(f"  {'-'*70} {'-'*7} {'-'*9} {'-'*9} {'-'*10}")
    for combo, s in summary_stats.items():
        label = f"GENDER={combo[0]}  ETHNICITY={combo[1]}  AGE_GROUP={combo[2]}"
        print(f"  {label:<70} {s['target']:>7} {s['accepted']:>9} "
              f"{s['attempts']:>9} {s['avg_auroc']:>10.3f}")

    if not all_accepted:
        return pd.DataFrame(), summary_stats
    return pd.concat(all_accepted, ignore_index=True), summary_stats


def _run_subgroup_healthgan(args_dict: dict) -> dict:
    """
    Process one (GENDER, ETHNICITY, AGE_GROUP) subgroup using HealthGAN.
    Trains a fresh HealthGAN on the subgroup's real data per attempt.
    Must run serially — os.chdir() inside HealthGAN is not thread-safe.
    """
    import shutil
    import tempfile

    combo           = args_dict['combo']
    target_count    = args_dict['target_count']
    encoder         = args_dict['encoder']
    subdata         = args_dict['subdata']
    nu              = args_dict['nu']
    gamma           = args_dict['gamma']
    seed            = args_dict['seed']
    auroc_threshold = args_dict['auroc_threshold']
    classifier_name = args_dict['classifier_name']
    max_attempts      = args_dict['max_attempts']
    batch_size        = args_dict['batch_size']
    epochs            = args_dict['epochs']
    nodes             = args_dict['nodes']
    critic            = args_dict['critic']
    healthgan_dir     = args_dict['healthgan_dir']
    min_subgroup_size = args_dict.get('min_subgroup_size', 10)

    gender, ethnicity, age_group = combo
    accepted               = []
    total_rows             = 0
    attempts               = 0
    auc_scores             = []
    lines                  = []
    consecutive_zero       = 0
    consecutive_auroc_fail = 0

    lines.append(f"\n  ── Subgroup  GENDER={gender}  ETHNICITY={ethnicity}  "
                 f"AGE_GROUP={age_group}  (target: {target_count}) ──")

    real_sub = subdata[
        (subdata['GENDER']    == gender) &
        (subdata['ETHNICITY'] == ethnicity) &
        (subdata['AGE_GROUP'] == age_group)
    ].copy()

    if len(real_sub) < min_subgroup_size:
        lines.append(f"    WARNING: Only {len(real_sub)} real rows — skipping (need ≥ {min_subgroup_size}).")
        return dict(combo=combo, accepted_df=None, target=target_count,
                    accepted=0, attempts=0, avg_auroc=float('nan'), log_lines=lines)

    # Per-subgroup OCSVM fitted on this subgroup's real rows
    X_sub = encoder.transform(real_sub.astype(str))
    ocsvm = OneClassSVM(kernel='rbf', nu=nu, gamma=gamma)
    ocsvm.fit(X_sub)
    lines.append(f"    OCSVM fitted on {len(real_sub)} real rows for this subgroup.")

    # For very small subgroups, batch_size = int(n_train / critic) // 100 * 100
    # can become 0 when n_train < critic * 100. Cap critic so batch_size ≥ 1.
    n_train_est = max(1, int(len(real_sub) * 0.8))
    effective_critic = min(critic, max(1, n_train_est // 100))
    if effective_critic != critic:
        lines.append(f"    INFO: critic reduced {critic}→{effective_critic} "
                     f"(subgroup too small for batch_size calc).")

    epoch_tag    = epochs - 1
    gan_filename = f"samples_{epoch_tag}_{effective_critic}_{nodes}_synthetic_0.csv"

    while total_rows < target_count and attempts < max_attempts:
        attempts += 1
        tmp_dir = tempfile.mkdtemp(prefix="healthgan_aug_")
        try:
            # Train/test split → save temp files
            train_data, test_data = train_test_split(
                real_sub, test_size=0.2, random_state=seed + attempts
            )
            train_file = os.path.join(tmp_dir, "train.csv")
            test_file  = os.path.join(tmp_dir, "test.csv")
            train_data.to_csv(train_file, index=False)
            test_data.to_csv(test_file,   index=False)

            # Encode to SDV format
            # dtype pins AGE_GROUP as str — otherwise pandas' CSV parser reads a
            # subgroup file whose AGE_GROUP column is all "+81" as int64, silently
            # dropping the "+" and creating a phantom "81" category downstream.
            from synthetic_data.generators.processing import Encoder, Decoder
            age_dtype = {'AGE_GROUP': str}
            en = Encoder()
            en.encode_train(train_file, dtype=age_dtype)
            en.encode_test(test_file, train_file, dtype=age_dtype)

            train_sdv = os.path.join(tmp_dir, "train_sdv.csv")
            test_sdv  = os.path.join(tmp_dir, "test_sdv.csv")

            if not os.path.exists(train_sdv):
                lines.append(f"    WARNING: Encoder did not produce train_sdv.csv — skipping.")
                continue

            # Train HealthGAN — must chdir to healthgan_dir (HealthGAN writes to ./gen_data/)
            from synthetic_data.generators.gan import HealthGAN
            os.makedirs(os.path.join(healthgan_dir, "gen_data"), exist_ok=True)

            original_cwd = os.getcwd()
            os.chdir(healthgan_dir)
            try:
                n_gen = batch_size
                gan = HealthGAN(
                    train_file   = train_sdv,
                    test_file    = test_sdv,
                    base_nodes   = nodes,
                    critic_iters = effective_critic,
                    num_epochs   = epochs,
                    n_samples    = n_gen,
                )
                gan.train()
            finally:
                os.chdir(original_cwd)

            gan_output = os.path.join(healthgan_dir, "gen_data", gan_filename)
            if not os.path.exists(gan_output):
                lines.append(f"    WARNING: GAN output not found: {gan_filename}")
                continue

            # Decode synthetic samples back to original feature space
            de = Decoder()
            de.decode(train_file, gan_output, dtype=age_dtype)

            decoded_file = os.path.join(tmp_dir, "train_decoded.csv")
            if not os.path.exists(decoded_file):
                lines.append(f"    WARNING: Decoded file not found — skipping.")
                continue

            sample = pd.read_csv(decoded_file)
            if sample.empty:
                lines.append(f"    [attempt {attempts:>3}] Empty sample — skipping.")
                continue

            # Gate 1: OCSVM
            try:
                X_synth    = encoder.transform(sample.astype(str))
                decision   = ocsvm.predict(X_synth)
                valid_rows = sample[decision == 1].copy()
            except Exception as e:
                lines.append(f"    WARNING: OCSVM transform failed ({e}) — accepting all.")
                valid_rows = sample.copy()

            if len(valid_rows) == 0:
                consecutive_zero += 1
                lines.append(f"    [attempt {attempts:>3}] OCSVM: 0/{len(sample)} passed"
                             f"  (patience {consecutive_zero}/{OCSVM_PATIENCE})")
                if consecutive_zero >= OCSVM_PATIENCE:
                    lines.append(f"    ⏹  Early stop: OCSVM rejected 100 % for "
                                 f"{consecutive_zero} consecutive batches.")
                    break
                continue
            consecutive_zero = 0

            # Gate 2: Classifier quality test
            n_balanced  = min(len(real_sub), len(valid_rows))
            real_sample = real_sub.sample(n=n_balanced, random_state=seed).copy()
            fake_sample = valid_rows.sample(n=n_balanced, random_state=seed).copy()

            lines.append(f"    [attempt {attempts:>3}] Classifier input: "
                         f"{n_balanced} real vs {n_balanced} synthetic (balanced)")

            if n_balanced < MIN_SAMPLES_CLASSIFIER:
                n_take = min(len(valid_rows), target_count - total_rows)
                accepted.append(valid_rows.iloc[:n_take])
                total_rows += n_take
                lines.append(f"    [attempt {attempts:>3}] OCSVM: {len(valid_rows)}/{len(sample)} "
                             f"passed  | classifier skipped (too few samples) "
                             f"→ accepted {n_take}  (total: {total_rows}/{target_count})")
                continue

            real_sample['_label'] = 1
            fake_sample['_label'] = 0
            clf_data = pd.concat([real_sample, fake_sample], ignore_index=True)
            X_clf    = encoder.transform(clf_data.drop(columns=['_label']).astype(str))
            y_clf    = clf_data['_label']

            if (y_clf == 0).sum() < 2 or (y_clf == 1).sum() < 2:
                n_take = min(len(valid_rows), target_count - total_rows)
                accepted.append(valid_rows.iloc[:n_take])
                total_rows += n_take
                lines.append(f"    [attempt {attempts:>3}] classifier skipped (class imbalance) "
                             f"→ accepted {n_take}  (total: {total_rows}/{target_count})")
                continue

            X_train, X_test, y_train, y_test = train_test_split(
                X_clf, y_clf, test_size=0.4, stratify=y_clf, random_state=seed
            )
            clf = get_classifier(classifier_name, seed)
            clf.fit(X_train, y_train)
            auc = roc_auc_score(y_test, clf.predict_proba(X_test)[:, 1])
            auc_scores.append(auc)

            if auc <= auroc_threshold:
                consecutive_auroc_fail = 0
                n_take = min(len(valid_rows), target_count - total_rows)
                accepted.append(valid_rows.iloc[:n_take])
                total_rows += n_take
                lines.append(f"    [attempt {attempts:>3}] OCSVM: {len(valid_rows)}/{len(sample)} "
                             f"passed  | AUROC={auc:.3f} ≤ {auroc_threshold} ✅ PASS"
                             f"→ accepted {n_take}  (total: {total_rows}/{target_count})")
            else:
                consecutive_auroc_fail += 1
                lines.append(f"    [attempt {attempts:>3}] OCSVM: {len(valid_rows)}/{len(sample)} "
                             f"passed  | AUROC={auc:.3f} > {auroc_threshold} FAIL→ rejected"
                             f"  (AUROC patience {consecutive_auroc_fail}/{AUROC_PATIENCE})")
                if consecutive_auroc_fail >= AUROC_PATIENCE:
                    lines.append(f"    ⏹  Early stop: AUROC failed for "
                                 f"{consecutive_auroc_fail} consecutive attempts.")
                    break

        except Exception as e:
            import traceback
            lines.append(f"    WARNING: Attempt {attempts} failed: {e}")
            lines.append(f"    {traceback.format_exc()}")
        finally:
            shutil.rmtree(tmp_dir, ignore_errors=True)

    avg_auc  = float(np.mean(auc_scores)) if auc_scores else float('nan')
    combo_df = None

    if total_rows > 0:
        combo_df = pd.concat(accepted, ignore_index=True).iloc[:target_count]
        lines.append(f"    → Final: {len(combo_df)}/{target_count} accepted  "
                     f"(avg AUROC: {avg_auc:.3f})")
    else:
        lines.append(f"    ❌ FAILED: No valid samples accepted.")

    return dict(combo=combo, accepted_df=combo_df, target=target_count,
                accepted=total_rows, attempts=attempts,
                avg_auroc=avg_auc, log_lines=lines)


def synthesize_healthgan(subdata: pd.DataFrame, sigma: dict, seed: int,
                          nu: float, gamma, auroc_threshold: float,
                          classifier_name: str, workers: int,
                          batch_size: int, max_tries_per_batch: int,
                          max_attempts: int,
                          epochs: int = 10000, nodes: int = 64,
                          critic: int = 5, aug_epochs: int = 1000,
                          min_subgroup_size: int = 10) -> tuple:
    """
    Conditional HealthGAN augmentation: trains one HealthGAN per underrepresented
    subgroup, applies OCSVM + classifier quality gates (same as CTGAN path).
    Always runs serially — os.chdir() inside HealthGAN is not thread-safe.
    aug_epochs controls per-subgroup training; epochs is for final synthesis only.
    """
    np.random.seed(seed)

    script_dir    = Path(os.path.dirname(os.path.abspath(__file__)))
    healthgan_dir = str(script_dir.parent / 'synthetic_data_generation' / 'healthgan')

    print(f"\n  HealthGAN augmentation: aug_epochs={aug_epochs}, nodes={nodes}, critic={critic}")
    if workers > 1:
        print("  WARNING: HealthGAN uses os.chdir() — running serially (workers ignored).")

    print(f"\n  Fitting OrdinalEncoder on full subdata ...")
    encoder = OrdinalEncoder(handle_unknown='use_encoded_value', unknown_value=-1)
    encoder.fit(subdata.astype(str))
    print(f"  Encoder fitted.  OCSVM will be fitted per subgroup "
          f"(nu={nu}, gamma={gamma}).")
    print(f"\n  Processing {len(sigma)} subgroup(s) sequentially ...")

    job_args = [
        dict(combo=combo, target_count=count,
             encoder=encoder, subdata=subdata,
             nu=nu, gamma=gamma,
             seed=seed, auroc_threshold=auroc_threshold,
             classifier_name=classifier_name,
             max_attempts=max_attempts,
             batch_size=batch_size,
             epochs=aug_epochs, nodes=nodes, critic=critic,
             healthgan_dir=healthgan_dir,
             min_subgroup_size=min_subgroup_size)
        for combo, count in sigma.items()
    ]

    results_map = {}
    for a in job_args:
        result = _run_subgroup_healthgan(a)
        for line in result['log_lines']:
            print(line, flush=True)
        results_map[result['combo']] = result

    all_accepted  = []
    summary_stats = {}

    for combo in sigma:
        r = results_map.get(combo)
        if r is None:
            continue
        summary_stats[combo] = {
            'target':    r['target'],
            'accepted':  r['accepted'],
            'attempts':  r['attempts'],
            'avg_auroc': r['avg_auroc'],
        }
        if r['accepted_df'] is not None:
            all_accepted.append(r['accepted_df'])

    print("\n  ── Generation summary ──────────────────────────────────────────")
    print(f"  {'Subgroup':<70} {'Target':>7} {'Accepted':>9} {'Attempts':>9} {'Avg AUROC':>10}")
    print(f"  {'-'*70} {'-'*7} {'-'*9} {'-'*9} {'-'*10}")
    for combo, s in summary_stats.items():
        label = f"GENDER={combo[0]}  ETHNICITY={combo[1]}  AGE_GROUP={combo[2]}"
        print(f"  {label:<70} {s['target']:>7} {s['accepted']:>9} "
              f"{s['attempts']:>9} {s['avg_auroc']:>10.3f}")

    if not all_accepted:
        return pd.DataFrame(), summary_stats
    return pd.concat(all_accepted, ignore_index=True), summary_stats


def _run_subgroup_medgan(args_dict: dict) -> dict:
    """
    Process one (GENDER, ETHNICITY, AGE_GROUP) subgroup using MedGAN.
    Trains MedGAN on the subgroup's real data, applies OCSVM + AUROC gates.
    Runs serially — subprocess calls write to fixed paths.
    """
    import shutil, tempfile, subprocess, pickle, sys

    combo           = args_dict['combo']
    target_count    = args_dict['target_count']
    encoder_ocsvm   = args_dict['encoder_ocsvm']
    subdata         = args_dict['subdata']
    nu              = args_dict['nu']
    gamma           = args_dict['gamma']
    seed            = args_dict['seed']
    auroc_threshold = args_dict['auroc_threshold']
    classifier_name = args_dict['classifier_name']
    max_attempts      = args_dict['max_attempts']
    aug_epochs        = args_dict['aug_epochs']
    batch_size        = args_dict['batch_size']
    medgan_dir        = args_dict['medgan_dir']
    min_subgroup_size = args_dict.get('min_subgroup_size', 10)

    gender, ethnicity, age_group = combo
    accepted               = []
    total_rows             = 0
    attempts               = 0
    auc_scores             = []
    lines                  = []
    consecutive_zero       = 0
    consecutive_auroc_fail = 0

    lines.append(f"\n  ── Subgroup  GENDER={gender}  ETHNICITY={ethnicity}  "
                 f"AGE_GROUP={age_group}  (target: {target_count}) ──")

    real_sub = subdata[
        (subdata['GENDER']    == gender) &
        (subdata['ETHNICITY'] == ethnicity) &
        (subdata['AGE_GROUP'] == age_group)
    ].copy()

    if len(real_sub) < min_subgroup_size:
        lines.append(f"    WARNING: Only {len(real_sub)} real rows — skipping (need >= {min_subgroup_size}).")
        return dict(combo=combo, accepted_df=None, target=target_count,
                    accepted=0, attempts=0, avg_auroc=float('nan'), log_lines=lines)

    # Per-subgroup OCSVM
    from sklearn.preprocessing import OneHotEncoder as OHE
    from sklearn.svm import OneClassSVM

    # Match HealthGAN/CTGAN's feature space so gamma='auto' is comparable.
    X_sub = encoder_ocsvm.transform(real_sub.astype(str))
    ocsvm = OneClassSVM(kernel='rbf', nu=nu, gamma=gamma)
    ocsvm.fit(X_sub)
    lines.append(f"    OCSVM fitted on {len(real_sub)} real rows for this subgroup.")

    los_values = real_sub['LOS'].dropna().values if 'LOS' in real_sub.columns else None
    cat_cols   = [c for c in real_sub.columns if c != 'LOS']

    medgan_script = os.path.join(medgan_dir, 'medgan.py')

    while total_rows < target_count and attempts < max_attempts:
        attempts += 1
        tmp_dir = tempfile.mkdtemp(prefix='medgan_aug_')
        try:
            mat_path   = os.path.join(tmp_dir, 'input.npy')
            model_path = os.path.join(tmp_dir, 'model', 'output')
            synth_path = os.path.join(tmp_dir, 'synthetic')
            os.makedirs(os.path.join(tmp_dir, 'model'), exist_ok=True)

            ohe_sub = OHE(handle_unknown='ignore', sparse=False)
            mat = ohe_sub.fit_transform(real_sub[cat_cols].astype(str)).astype(np.float32)
            pickle.dump(mat.astype(int), open(mat_path, 'wb'), -1)

            # Train
            train_cmd = [
                sys.executable, medgan_script,
                mat_path, model_path,
                '--data_type', 'binary',
                '--n_epoch', str(aug_epochs),
                '--n_pretrain_epoch', str(min(100, aug_epochs // 10)),
                '--batch_size', str(max(1, min(100, len(real_sub)))),
                '--save_max_keep', '1',
            ]
            r = subprocess.run(train_cmd, cwd=medgan_dir,
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            if r.returncode != 0:
                lines.append(f"    WARNING: Attempt {attempts} — MedGAN training failed.")
                continue

            model_file = f"{model_path}-{aug_epochs - 1}"
            if not os.path.exists(model_file + '.index'):
                lines.append(f"    WARNING: Attempt {attempts} — model checkpoint not found.")
                continue

            # Generate — batch_size controls both the generation chunk size and
            # the total number of samples produced per attempt
            gen_cmd = [
                sys.executable, medgan_script,
                mat_path, synth_path,
                '--data_type', 'binary',
                '--generate_data', 'True',
                '--model_file', model_file,
                '--batch_size', str(batch_size),
                '--n_samples', str(batch_size),
            ]
            r = subprocess.run(gen_cmd, cwd=medgan_dir,
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            synth_npy = synth_path + '.npy'
            if r.returncode != 0 or not os.path.exists(synth_npy):
                lines.append(f"    WARNING: Attempt {attempts} — MedGAN generation failed.")
                continue

            # Decode
            raw     = np.load(synth_npy, allow_pickle=True)
            decoded = ohe_sub.inverse_transform(raw.astype(int))
            valid_mask = np.array([not any(x is None for x in row) for row in decoded])
            decoded    = decoded[valid_mask]
            if len(decoded) == 0:
                lines.append(f"    WARNING: Attempt {attempts} — all decoded rows are None.")
                continue

            sample = pd.DataFrame(decoded, columns=cat_cols)
            if los_values is not None:
                sample['LOS'] = np.random.choice(los_values, size=len(sample), replace=True)

            # Gate 1: OCSVM
            try:
                X_synth    = encoder_ocsvm.transform(sample[real_sub.columns].astype(str))
                decision   = ocsvm.predict(X_synth)
                valid_rows = sample[decision == 1].copy()
            except Exception as e:
                lines.append(f"    WARNING: OCSVM transform failed ({e}) — accepting all.")
                valid_rows = sample.copy()

            if len(valid_rows) == 0:
                consecutive_zero += 1
                lines.append(f"    [attempt {attempts:>3}] OCSVM: 0/{len(sample)} passed"
                             f"  (patience {consecutive_zero}/{OCSVM_PATIENCE})")
                if consecutive_zero >= OCSVM_PATIENCE:
                    lines.append(f"    ⏹  Early stop: OCSVM rejected 100 % for "
                                 f"{consecutive_zero} consecutive batches.")
                    break
                continue
            consecutive_zero = 0

            # Gate 2: Classifier AUROC
            # real_sub has no LOS (dropped by build_subdata); valid_rows has LOS
            # re-attached after decoding. Use cat_cols for fake_sample so both
            # sides have the same columns as encoder_ocsvm was fit on.
            n_balanced  = min(len(real_sub), len(valid_rows))
            real_sample = real_sub.sample(n=n_balanced, random_state=seed).copy()
            fake_sample = valid_rows[cat_cols].sample(n=n_balanced, random_state=seed).copy()

            lines.append(f"    [attempt {attempts:>3}] Classifier input: "
                         f"{n_balanced} real vs {n_balanced} synthetic (balanced)")

            if n_balanced < MIN_SAMPLES_CLASSIFIER:
                n_take = min(len(valid_rows), target_count - total_rows)
                accepted.append(valid_rows.iloc[:n_take])
                total_rows += n_take
                lines.append(f"    [attempt {attempts:>3}] OCSVM: {len(valid_rows)}/{len(sample)} "
                             f"passed  | classifier skipped (too few samples) "
                             f"-> accepted {n_take}  (total: {total_rows}/{target_count})")
                continue

            real_sample['_label'] = 1
            fake_sample['_label'] = 0
            clf_data = pd.concat([real_sample, fake_sample], ignore_index=True)
            X_clf = encoder_ocsvm.transform(
                clf_data.drop(columns=['_label']).astype(str))
            y_clf = clf_data['_label']

            if (y_clf == 0).sum() < 2 or (y_clf == 1).sum() < 2:
                n_take = min(len(valid_rows), target_count - total_rows)
                accepted.append(valid_rows.iloc[:n_take])
                total_rows += n_take
                lines.append(f"    [attempt {attempts:>3}] classifier skipped (class imbalance) "
                             f"-> accepted {n_take}  (total: {total_rows}/{target_count})")
                continue

            from sklearn.model_selection import train_test_split
            from sklearn.metrics import roc_auc_score
            X_tr, X_te, y_tr, y_te = train_test_split(
                X_clf, y_clf, test_size=0.4, stratify=y_clf, random_state=seed)
            clf = get_classifier(classifier_name, seed)
            clf.fit(X_tr, y_tr)
            auc = roc_auc_score(y_te, clf.predict_proba(X_te)[:, 1])
            auc_scores.append(auc)

            vr_clean = valid_rows.copy()
            if auc <= auroc_threshold:
                consecutive_auroc_fail = 0
                n_take = min(len(vr_clean), target_count - total_rows)
                accepted.append(vr_clean.iloc[:n_take])
                total_rows += n_take
                lines.append(f"    [attempt {attempts:>3}] OCSVM: {len(valid_rows)}/{len(sample)} "
                             f"passed  | AUROC={auc:.3f} <= {auroc_threshold} ✅ PASS"
                             f"-> accepted {n_take}  (total: {total_rows}/{target_count})")
            else:
                consecutive_auroc_fail += 1
                lines.append(f"    [attempt {attempts:>3}] OCSVM: {len(valid_rows)}/{len(sample)} "
                             f"passed  | AUROC={auc:.3f} > {auroc_threshold} FAIL -> rejected"
                             f"  (AUROC patience {consecutive_auroc_fail}/{AUROC_PATIENCE})")
                if consecutive_auroc_fail >= AUROC_PATIENCE:
                    lines.append(f"    ⏹  Early stop: AUROC failed for "
                                 f"{consecutive_auroc_fail} consecutive attempts.")
                    break

        except Exception as e:
            import traceback
            lines.append(f"    WARNING: Attempt {attempts} failed: {e}")
            lines.append(f"    {traceback.format_exc()}")
        finally:
            shutil.rmtree(tmp_dir, ignore_errors=True)

    avg_auc  = float(np.mean(auc_scores)) if auc_scores else float('nan')
    combo_df = None
    if total_rows > 0:
        combo_df = pd.concat(accepted, ignore_index=True).iloc[:target_count]
        lines.append(f"    -> Final: {len(combo_df)}/{target_count} accepted  "
                     f"(avg AUROC: {avg_auc:.3f})")
    else:
        lines.append(f"    ❌ FAILED: No valid samples accepted.")

    return dict(combo=combo, accepted_df=combo_df, target=target_count,
                accepted=total_rows, attempts=attempts,
                avg_auroc=avg_auc, log_lines=lines)


