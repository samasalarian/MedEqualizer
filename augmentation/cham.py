def parse_args():
    p = argparse.ArgumentParser(
        description='MedEqualizer – fairness-aware data augmentation',
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument('--dataset',    required=True, choices=['mimic3', 'mimic4'])
    p.add_argument('--model',      required=True,
                   choices=['ctgan', 'healthgan', 'medgan'])
    p.add_argument('--tau',        required=True, type=int,
                   help='Groups with count < tau are augmented')
    p.add_argument('--nu',         type=float, default=0.05,
                   help='One-Class SVM nu (outlier fraction bound)')
    p.add_argument('--gamma',      type=str,   default='scale',
                   help="One-Class SVM gamma: 'scale', 'auto', or a float e.g. '0.1'")
    p.add_argument('--auroc',      type=float, default=0.75,
                   help='Batches with AUROC <= this are accepted (lower = stricter)')
    p.add_argument('--classifier', default='random_forest',
                   choices=['random_forest', 'logistic_regression',
                            'gradient_boosting', 'decision_tree', 'svm'])
    p.add_argument('--workers',    type=int, default=1,
                   help='Number of parallel subgroup workers. '
                        'Recommended: 4 on M1 Pro, up to cpu_count//2.')
    p.add_argument('--batch_size', type=int, default=500,
                   help='Number of rows requested per CTGAN batch')
    p.add_argument('--max_tries',  type=int, default=300,
                   help='Max SDV internal retries per batch')
    p.add_argument('--max_attempts', type=int, default=100,
                   help='Max outer generation loop iterations per subgroup')
    p.add_argument('--seed',       type=int, default=42)
    # HealthGAN-specific (ignored for ctgan / medgan)
    p.add_argument('--epochs', type=int, default=10000,
                   help='HealthGAN epochs for final synthesis (healthgan only)')
    p.add_argument('--aug_epochs', type=int, default=1000,
                   help='HealthGAN epochs per subgroup augmentation attempt (healthgan only)')
    p.add_argument('--nodes',  type=int, default=64,
                   help='HealthGAN base nodes (healthgan only)')
    p.add_argument('--critic', type=int, default=5,
                   help='HealthGAN critic iterations (healthgan only)')
    p.add_argument('--min_subgroup_size', type=int, default=10,
                   help='Minimum real rows in a subgroup to attempt augmentation')
    p.add_argument('--input_path', default=None,
                   help='Path to real CSV '
                        '(default: <base_dir>/data/<Dataset>/real/real.csv)')
    p.add_argument('--output_path', default=None,
                   help='Explicit augmented CSV output path. The legacy '
                        'data/<Dataset>/augmented/<model>/ path is used when omitted.')
    p.add_argument('--log_output_path', default=None,
                   help='Explicit augmentation Excel log path. The legacy '
                        'data/augmentation_counts_<model>.xlsx path is used when omitted.')
    p.add_argument('--base_dir',   default=None,
                   help='Project root (default: parent of this script)')
    p.add_argument('--categorized', action='store_true',
                   help='Use real_categorized.csv as input and write output to '
                        '{model}_cat directory')
    return p.parse_args()


# ═══════════════════════════════════════════════════════════════════════════════
# Main
# ═══════════════════════════════════════════════════════════════════════════════

def main():
    args = parse_args()

    try:
        gamma = float(args.gamma)
    except ValueError:
        gamma = args.gamma

    script_dir  = Path(os.path.dirname(os.path.abspath(__file__)))
    base_dir    = Path(args.base_dir) if args.base_dir else script_dir.parent
    dataset_cap = 'Mimic3' if args.dataset == 'mimic3' else 'Mimic4'

    model_dir = f"{args.model}_cat" if args.categorized else args.model

    if args.input_path:
        input_path = Path(args.input_path)
    elif args.categorized:
        input_path = base_dir / 'data' / dataset_cap / 'real' / 'real_categorized.csv'
    else:
        input_path = base_dir / 'data' / dataset_cap / 'real' / 'real.csv'

    gamma_str = str(gamma).replace('.', 'p')
    nu_str    = str(args.nu).replace('.', 'p')
    auroc_str = str(args.auroc).replace('.', 'p')
    if args.output_path:
        out_file = Path(args.output_path).expanduser().resolve()
    else:
        out_dir = base_dir / 'data' / dataset_cap / 'augmented' / model_dir
        out_file = out_dir / f'{args.tau}_{nu_str}_{gamma_str}_{auroc_str}_{args.classifier}.csv'
    out_file.parent.mkdir(parents=True, exist_ok=True)

    if args.log_output_path:
        excel_path = str(Path(args.log_output_path).expanduser().resolve())
    else:
        excel_path = str(base_dir / 'data' / f'augmentation_counts_{model_dir}.xlsx')
    Path(excel_path).parent.mkdir(parents=True, exist_ok=True)

    # ── Banner ─────────────────────────────────────────────────────────────────
    print("=" * 64)
    print("  MedEqualizer  –  Fairness-Aware Data Augmentation")
    print("=" * 64)
    print(f"  Dataset        : {args.dataset.upper()}")
    print(f"  Model          : {args.model.upper()}")
    print(f"  Tau            : {args.tau}")
    print(f"  Seed           : {args.seed}")
    print(f"  OCSVM nu       : {args.nu}")
    print(f"  OCSVM gamma    : {gamma}")
    print(f"  AUROC thresh   : {args.auroc}")
    print(f"  Classifier     : {args.classifier}")
    print(f"  Workers        : {args.workers}")
    print(f"  Batch size     : {args.batch_size}")
    print(f"  Max tries      : {args.max_tries}")
    print(f"  Max attempts   : {args.max_attempts}")
    print(f"  OCSVM patience : {OCSVM_PATIENCE} consecutive zero batches → skip")
    print(f"  AUROC patience : {AUROC_PATIENCE} consecutive Gate-2 failures → skip")
    print(f"  Input          : {input_path}")
    print(f"  Output         : {out_file}")
    print(f"  Excel log      : {excel_path}")
    print("=" * 64)

    # ── [1] Load ───────────────────────────────────────────────────────────────
    print("\n[1/5] Loading real data ...")
    df = pd.read_csv(input_path)
    print(f"  Loaded {len(df):,} rows × {len(df.columns)} columns")

    # ── [2] Distributions ──────────────────────────────────────────────────────
    print("\n[2/5] Equity column distributions ...")
    print(f"  GENDER:\n{df['GENDER'].value_counts().to_string()}")
    print(f"\n  ETHNICITY:\n{df['ETHNICITY'].value_counts().to_string()}")
    print(f"\n  AGE_GROUP:\n{df['AGE_GROUP'].value_counts().to_string()}")

    # ── [3] Underrepresented groups ────────────────────────────────────────────
    print(f"\n[3/5] Identifying underrepresented groups (count < tau={args.tau}) ...")
    under = get_underrepresented(df, args.tau)
    if under.empty:
        print(f" PASS No underrepresented groups. Nothing to augment.")
        sys.exit(2)  # sentinel: caller should stop pipeline gracefully
    print(f"\n  {len(under)} underrepresented group(s):")
    print(under[EQUITY_COLS + ['count', 'gap']].to_string(index=False))
    sigma = greedy_sigma(under)
    print(f"\n  Total records targeted: {sum(sigma.values()):,}")

    # ── [4] Build subdata ──────────────────────────────────────────────────────
    print("\n[4/5] Preparing subdata ...")
    subdata = build_subdata(df)
    print(f"  {subdata.shape[0]:,} rows × {subdata.shape[1]} columns")
    print(f"  Columns: {list(subdata.columns)}")

    # ── [5] Generate ──────────────────────────────────────────────────────────
    print(f"\n[5/5] Running {args.model.upper()} generation loop ...")
    synth_fn = SYNTH_FN[args.model]
    df_synth, summary_stats = synth_fn(
        subdata, sigma, args.seed,
        nu=args.nu, gamma=gamma,
        auroc_threshold=args.auroc,
        classifier_name=args.classifier,
        workers=args.workers,
        batch_size=args.batch_size,
        max_tries_per_batch=args.max_tries,
        max_attempts=args.max_attempts,
        epochs=args.epochs,
        aug_epochs=args.aug_epochs,
        nodes=args.nodes,
        critic=args.critic,
        min_subgroup_size=args.min_subgroup_size,
    )

    n_augmented = len(df_synth)

    # ── Save CSV ───────────────────────────────────────────────────────────────
    print("\n  Saving results ...")
    df['source'] = 'real'
    if n_augmented > 0:
        df_synth['source'] = 'synthetic'
        combined = pd.concat([df, df_synth], ignore_index=True, sort=False)
    else:
        print("  WARNING: No synthetic records accepted — saving real data only.")
        combined = df

    combined.to_csv(out_file, index=False)

    print(f"\n  Output file    : {out_file}")
    print(f"  Original rows  : {len(df):,}")
    print(f"  Augmented rows : {n_augmented:,}")
    print(f"  Total rows     : {len(combined):,}")

    # ── Per-subgroup summary ───────────────────────────────────────────────────
    subgroup_rows = [
        {
            'dataset':         args.dataset,
            'model':           args.model,
            'tau':             args.tau,
            'ocsvm_nu':        args.nu,
            'ocsvm_gamma':     str(gamma),
            'auroc_threshold': args.auroc,
            'classifier':      args.classifier,
            'GENDER':          combo[0],
            'ETHNICITY':       combo[1],
            'AGE_GROUP':       combo[2],
            'target':          s['target'],
            'accepted':        s['accepted'],
            'attempts':        s['attempts'],
            'avg_auroc':       round(s['avg_auroc'], 4) if not np.isnan(s['avg_auroc']) else None,
        }
        for combo, s in summary_stats.items()
    ]
    df_subgroups = pd.DataFrame(subgroup_rows)

    print("\n  Per-subgroup augmentation counts:")
    print(df_subgroups[['GENDER', 'ETHNICITY', 'AGE_GROUP', 'target', 'accepted',
                         'attempts', 'avg_auroc']].to_string(index=False))

    # ── Excel log: 'runs' sheet + 'subgroups' sheet ────────────────────────────
    import datetime
    run_ts = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')

    log_row = {
        'run_timestamp': run_ts,
        'dataset': args.dataset, 'model': args.model, 'tau': args.tau,
        'seed': args.seed, 'ocsvm_nu': args.nu, 'ocsvm_gamma': str(gamma),
        'auroc_threshold': args.auroc, 'classifier': args.classifier,
        'workers': args.workers, 'batch_size': args.batch_size,
        'max_tries': args.max_tries, 'max_attempts': args.max_attempts,
        'original_rows': len(df), 'underrep_groups': len(under),
        'targeted_records': sum(sigma.values()),
        'augmented_records': n_augmented, 'total_rows': len(combined),
        'output_file': str(out_file),
    }

    if os.path.exists(excel_path):
        try:
            existing_runs = pd.read_excel(excel_path, sheet_name='runs', engine='openpyxl')
        except Exception:
            existing_runs = pd.DataFrame()
        try:
            existing_sg = pd.read_excel(excel_path, sheet_name='subgroups', engine='openpyxl')
        except Exception:
            existing_sg = pd.DataFrame()
    else:
        existing_runs = pd.DataFrame()
        existing_sg   = pd.DataFrame()

    new_runs = pd.concat([existing_runs, pd.DataFrame([log_row])], ignore_index=True)
    new_sg   = pd.concat([existing_sg,   df_subgroups],            ignore_index=True)

    # Always rewrite the whole file (rather than append in-place) since the
    # installed pandas/openpyxl version doesn't support if_sheet_exists='replace'
    # and silently creates duplicate sheets (runs1, runs2, ...) otherwise.
    with pd.ExcelWriter(excel_path, engine='openpyxl', mode='w') as writer:
        new_runs.to_excel(writer, sheet_name='runs',      index=False)
        new_sg.to_excel(  writer, sheet_name='subgroups', index=False)

    print(f"\n  Excel log saved : {excel_path}")
    print(f"    'runs'        : one row per run")
    print(f"    'subgroups'   : one row per subgroup per run")
    print("\n" + "=" * 64)
    print("  Augmentation complete.")
    print("=" * 64)


if __name__ == '__main__':
    main()
